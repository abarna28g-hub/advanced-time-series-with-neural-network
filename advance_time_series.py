@dataclass
class DataConfig:
    input_length: int = 60   # number of past days fed into model
    horizon: int = 14        # forecast horizon in days
    test_size: int = 365     # last year for test
    val_size: int = 365      # year for validation before test
    batch_size: int = 64


def train_val_test_split(df: pd.DataFrame, config: DataConfig):
    """
    Split the time series into train/val/test contiguous blocks.
    """
    n = len(df)
    test_start = n - config.test_size
    val_start = n - config.test_size - config.val_size

    df_train = df.iloc[:val_start]
    df_val = df.iloc[val_start:test_start]
    df_test = df.iloc[test_start:]

    return df_train, df_val, df_test


def create_supervised(
    df: pd.DataFrame,
    config: DataConfig,
    scalers: Dict[str, StandardScaler] = None,
    fit_scalers: bool = False
):
    """
    Transform time series into supervised learning format:
    X: [n_samples, input_length, n_features]
    y: [n_samples, horizon]
    Features include lagged target and exogenous variables at each lag step.
    """
    values = df.copy()

    feature_cols = ["y", "temp", "promo"]
    values = values[feature_cols].values.astype(np.float32)

    if scalers is None:
        scalers = {col: StandardScaler() for col in range(values.shape[1])}

    # Apply scaling per feature column
    if fit_scalers:
        for i in range(values.shape[1]):
            scalers[i].fit(values[:, i:i+1])
            values[:, i:i+1] = scalers[i].transform(values[:, i:i+1])
    else:
        for i in range(values.shape[1]):
            values[:, i:i+1] = scalers[i].transform(values[:, i:i+1])

    X, y = [], []
    total_len = config.input_length + config.horizon

    for i in range(len(values) - total_len + 1):
        window = values[i: i + total_len]
        X.append(window[: config.input_length])
        # y is ONLY the target variable "y", which is first column
        y.append(window[config.input_length:, 0])

    X = np.stack(X)  # [n_samples, input_length, n_features]
    y = np.stack(y)  # [n_samples, horizon]

    return X, y, scalers


class TimeSeriesDataset(Dataset):
    def __init__(self, X: np.ndarray, y: np.ndarray):
        self.X = torch.from_numpy(X).float()
        self.y = torch.from_numpy(y).float()

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]


