def main():
    # ---- Configs ----
    data_cfg = DataConfig()
    print("Generating synthetic dataset...")
    df = generate_synthetic_time_series()

    # ---- Train/Val/Test split ----
    df_train, df_val, df_test = train_val_test_split(df, data_cfg)
    print(f"Train: {df_train.index[0]} to {df_train.index[-1]} | n={len(df_train)}")
    print(f"Val:   {df_val.index[0]} to {df_val.index[-1]} | n={len(df_val)}")
    print(f"Test:  {df_test.index[0]} to {df_test.index[-1]} | n={len(df_test)}")

    # ---- Supervised transformation ----
    X_train, y_train, scalers = create_supervised(
        df_train, data_cfg, scalers=None, fit_scalers=True
    )
    X_val, y_val, _ = create_supervised(
        df_val, data_cfg, scalers=scalers, fit_scalers=False
    )
    X_test, y_test, _ = create_supervised(
        df_test, data_cfg, scalers=scalers, fit_scalers=False
    )

    print(f"Supervised shapes | X_train: {X_train.shape}, y_train: {y_train.shape}")

    # ---- Hyperparameter tuning on train+val supervised samples ----
    X_tune = np.concatenate([X_train, X_val], axis=0)
    y_tune = np.concatenate([y_train, y_val], axis=0)
    print("Starting hyperparameter tuning (random search with rolling-origin CV)...")
    best_train_cfg = tune_hyperparameters(X_tune, y_tune, data_cfg, n_trials=5)

    # ---- Final train on train+val, evaluate on test ----
    print("Training final LSTM model on train+val...")
    model, history = train_one_model(
        X_tune,
        y_tune,
        X_val,
        y_val,  # still used for monitoring
        data_cfg,
        best_train_cfg,
    )

    device = best_train_cfg.device

    # Predictions on test supervised samples
    model.eval()
    with torch.no_grad():
        X_test_t = torch.from_numpy(X_test).float().to(device)
        y_pred_test = model(X_test_t).cpu().numpy()

    # Flatten for metrics
    y_true_flat = y_test.flatten()
    y_pred_flat = y_pred_test.flatten()

    # y_train_raw for MASE denominator (use original scale training y)
    y_train_raw = df_train["y"].values

    rmse_lstm = rmse(y_true_flat, y_pred_flat)
    smape_lstm = smape(y_true_flat, y_pred_flat)
    mase_lstm = mase(y_true_flat, y_pred_flat, y_train_raw, m=7)

    print(f"LSTM Test RMSE: {rmse_lstm:.4f}")
    print(f"LSTM Test SMAPE: {smape_lstm:.4f}")
    print(f"LSTM Test MASE: {mase_lstm:.4f}")

    # ---- Explainability: Permutation importance on lags ----
    base_rmse = rmse_lstm
    df_imp = compute_permutation_importance_lags(
        model, X_test, y_test, base_rmse, device=device
    )
    print("Top 10 most important lags (by delta RMSE):")
    print(df_imp.head(10).to_string(index=False))
    # Optional visualization:
    # plot_lag_importances(df_imp)

    # ---- Statistical baseline: SARIMAX ----
    print("Fitting SARIMAX baseline...")
    _ = fit_sarimax_baseline(df_train, df_val)

    # Forecasting over test period using SARIMAX (train+val fit)
    df_train_val = pd.concat([df_train, df_val])
    endog_train_val = df_train_val["y"]
    exog_train_val = df_train_val[["temp", "promo"]]

    model_full = sm.tsa.statespace.SARIMAX(
        endog=endog_train_val,
        exog=exog_train_val,
        order=(1, 1, 1),
        seasonal_order=(1, 1, 1, 7),
        enforce_stationarity=False,
        enforce_invertibility=False,
    )
    res_full = model_full.fit(disp=False)

    pred_test = res_full.get_prediction(
        start=df_test.index[0],
        end=df_test.index[-1],
        exog=df_test[["temp", "promo"]],
    )
    sarimax_pred = pred_test.predicted_mean.values

    rmse_sarimax = rmse(df_test["y"].values, sarimax_pred)
    smape_sarimax = smape(df_test["y"].values, sarimax_pred)
    mase_sarimax = mase(
        df_test["y"].values, sarimax_pred, y_train_raw, m=7
    )

    print(f"SARIMAX Test RMSE: {rmse_sarimax:.4f}")
    print(f"SARIMAX Test SMAPE: {smape_sarimax:.4f}")
    print(f"SARIMAX Test MASE: {mase_sarimax:.4f}")

    # ---- Summary table ----
    summary = pd.DataFrame(
        {
            "Model": ["LSTM", "SARIMAX"],
            "RMSE": [rmse_lstm, rmse_sarimax],
            "SMAPE": [smape_lstm, smape_sarimax],
            "MASE": [mase_lstm, mase_sarimax],
        }
    )
    print("\nFinal evaluation metrics on TEST set:")
    print(summary.to_string(index=False))

    # ---- Example forecast plot: LSTM vs SARIMAX vs actual ----
    n_plot = 3  # number of forecast windows to plot
    start_idx = data_cfg.input_length
    end_idx = start_idx + n_plot * data_cfg.horizon

    time_index = df_test.index[start_idx:end_idx]
    actual_series = df_test["y"].values[start_idx:end_idx]

    lstm_series = y_pred_test[:n_plot].reshape(-1)
    sarimax_series = sarimax_pred[start_idx:end_idx]

    plt.figure(figsize=(12, 6))
    plt.plot(time_index, actual_series, label="Actual", linewidth=2)
    plt.plot(time_index, lstm_series, label="LSTM forecast", linestyle="--")
    plt.plot(time_index, sarimax_series, label="SARIMAX forecast", linestyle=":")

    plt.title("Example forecasts on test set")
    plt.xlabel("Date")
    plt.ylabel("Value")
    plt.legend()
    plt.tight_layout()
    plt.show()


if __name__ == "__main__":
    main()