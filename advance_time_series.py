# =========================

def fit_sarimax_baseline(
    df_train: pd.DataFrame,
    df_val: pd.DataFrame,
    order=(1, 1, 1),
    seasonal_order=(1, 1, 1, 7),
):
    """
    Fit a SARIMAX model on train+val and evaluate on val.
    """
    endog_train = df_train["y"]
    exog_train = df_train[["temp", "promo"]]
    endog_val = df_val["y"]
    exog_val = df_val[["temp", "promo"]]

    model = sm.tsa.statespace.SARIMAX(
        endog=endog_train,
        exog=exog_train,
        order=order,
        seasonal_order=seasonal_order,
        enforce_stationarity=False,
        enforce_invertibility=False,
    )
    res = model.fit(disp=False)

    pred = res.get_prediction(
        start=endog_val.index[0],
        end=endog_val.index[-1],
        exog=exog_val,
    )
    yhat = pred.predicted_mean.values
    rmse_val = np.sqrt(mean_squared_error(endog_val.values, yhat))
    print(f"SARIMAX validation RMSE: {rmse_val:.4f}")
    return res


