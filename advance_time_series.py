def rmse(y_true, y_pred):
    return np.sqrt(mean_squared_error(y_true, y_pred))


def smape(y_true, y_pred, epsilon=1e-8):
    """
    Symmetric Mean Absolute Percentage Error.
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    denominator = (np.abs(y_true) + np.abs(y_pred) + epsilon) / 2.0
    diff = np.abs(y_true - y_pred) / denominator
    return np.mean(diff) * 100.0


def mase(y_true, y_pred, y_train, m: int = 7):
    """
    Mean Absolute Scaled Error.
    y_train: in-sample training target series used for naive seasonal forecast.
    m: seasonal period (e.g., 7 for weekly seasonality on daily data).
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    y_train = np.asarray(y_train)

    # Denominator: MAE of seasonal naive forecast on training data
    if len(y_train) <= m:
        raise ValueError("y_train length must be greater than seasonal period m.")
    naive_forecast = y_train[m:]
    naive_actual = y_train[:-m]
    mae_naive = np.mean(np.abs(naive_forecast - naive_actual))

    return np.mean(np.abs(y_true - y_pred)) / mae_naive


# =========================
# 7. EXPLAINABILITY: Permutation Importance over lags
# =========================

def compute_permutation_importance_lags(
    model: nn.Module,
    X_val: np.ndarray,
    y_val: np.ndarray,
    base_rmse: float,
    device: str,
) -> pd.DataFrame:
    """
    Permute each lag (time step) in the input sequence and measure increase in RMSE.
    This tells us which past lags are most important.
    """
    model.eval()
    n_samples, input_length, n_features = X_val.shape
    importances = []

    for lag in range(input_length):
        X_perm = X_val.copy()
        # Shuffle the entire feature vector at this lag across samples
        shuffled = np.random.permutation(X_perm[:, lag, :])
        X_perm[:, lag, :] = shuffled

        with torch.no_grad():
            X_t = torch.from_numpy(X_perm).float().to(device)
            preds = model(X_t).cpu().numpy()
        rmse_perm = rmse(y_val.flatten(), preds.flatten())
        delta = rmse_perm - base_rmse
        importances.append({"lag": lag + 1, "rmse": rmse_perm, "delta_rmse": delta})

    df_imp = pd.DataFrame(importances).sort_values("delta_rmse", ascending=False)
    return df_imp


def plot_lag_importances(df_imp: pd.DataFrame):
    plt.figure(figsize=(10, 4))
    plt.bar(df_imp["lag"], df_imp["delta_rmse"])
    plt.xlabel("Lag (days back from forecast origin)")
    plt.ylabel("Increase in RMSE when permuted")
    plt.title("Permutation Importance over Lag Steps")
    plt.tight_layout()
    plt.show()


