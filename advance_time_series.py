def generate_synthetic_time_series(
    n_days: int = 5 * 365,
    freq: str = "D"
) -> pd.DataFrame:
    """
    Generate a univariate time series with:
    - trend
    - weekly and yearly seasonality
    - regime change
    - exogenous variables (temperature-like and promo flag)
    """
    idx = pd.date_range(start="2010-01-01", periods=n_days, freq=freq)
    t = np.arange(n_days)

    # Global trend
    trend = 0.02 * t

    # Yearly and weekly seasonality
    yearly = 10 * np.sin(2 * np.pi * t / 365.25)
    weekly = 3 * np.sin(2 * np.pi * t / 7)

    # Regime change in middle of series
    regime = np.where(t < n_days // 2, 0, 15)

    # Noise
    noise = np.random.normal(loc=0.0, scale=2.5, size=n_days)

    # Exogenous: temperature-like seasonal variable
    temp = 15 + 10 * np.sin(2 * np.pi * (t - 30) / 365.25) + np.random.normal(0, 1.5, n_days)

    # Exogenous: promo flag (occasional 1s)
    promo = (np.random.rand(n_days) < 0.05).astype(float)

    # Target series depends on exogenous vars
    y = 20 + trend + yearly + weekly + regime + 0.5 * temp + 8 * promo + noise

    df = pd.DataFrame(
        {
            "ds": idx,
            "y": y,
            "temp": temp,
            "promo": promo,
        }
    ).set_index("ds")

    return df


