# 4. HYPERPARAMETER TUNING (simple random search + rolling-origin CV)
# =========================

def rolling_origin_splits(
    n_samples: int,
    n_splits: int = 3,
    train_fraction: float = 0.6,
):
    """
    Generate indices for rolling-origin evaluation over supervised samples.
    This operates on the supervised dataset indices (already windowed).
    """
    indices = np.arange(n_samples)
    initial_train_size = int(train_fraction * n_samples)
    remaining = n_samples - initial_train_size
    fold_size = max(1, remaining // n_splits)

    for i in range(n_splits):
        train_end = initial_train_size + i * fold_size
        val_end = train_end + fold_size
        if val_end > n_samples:
            break
        train_idx = indices[:train_end]
        val_idx = indices[train_end:val_end]
        if len(train_idx) == 0 or len(val_idx) == 0:
            continue
        yield train_idx, val_idx


def tune_hyperparameters(
    X: np.ndarray,
    y: np.ndarray,
    data_config: DataConfig,
    n_trials: int = 5,
) -> TrainingConfig:
    """
    Very small random search over hyperparameters using rolling-origin CV.
    You can replace this with more sophisticated Bayesian optimization if desired.
    """
    device = "cuda" if torch.cuda.is_available() else "cpu"

    hidden_size_choices = [32, 64, 128]
    num_layers_choices = [1, 2, 3]
    dropout_choices = [0.0, 0.1, 0.3]
    lr_choices = [1e-3, 5e-4]
    weight_decay_choices = [0.0, 1e-4]

    best_cfg = None
    best_score = np.inf

    for trial in range(n_trials):
        cfg = TrainingConfig(
            epochs=10,  # fewer epochs for tuning
            lr=float(np.random.choice(lr_choices)),
            weight_decay=float(np.random.choice(weight_decay_choices)),
            hidden_size=int(np.random.choice(hidden_size_choices)),
            num_layers=int(np.random.choice(num_layers_choices)),
            dropout=float(np.random.choice(dropout_choices)),
            device=device,
        )

        rmses = []
        for train_idx, val_idx in rolling_origin_splits(len(X), n_splits=3):
            X_train, y_train = X[train_idx], y[train_idx]
            X_val, y_val = X[val_idx], y[val_idx]

            model, _ = train_one_model(
                X_train, y_train, X_val, y_val, data_config, cfg
            )

            # Evaluate RMSE on this fold
            model.eval()
            with torch.no_grad():
                X_val_t = torch.from_numpy(X_val).float().to(cfg.device)
                preds = model(X_val_t).cpu().numpy()
            rmse_val = np.sqrt(mean_squared_error(y_val.flatten(), preds.flatten()))
            rmses.append(rmse_val)

        if len(rmses) == 0:
            continue

        avg_rmse = float(np.mean(rmses))
        print(
            f"[TUNING] Trial {trial+1}/{n_trials} | "
            f"hidden={cfg.hidden_size} layers={cfg.num_layers} "
            f"dropout={cfg.dropout} lr={cfg.lr} wd={cfg.weight_decay} "
            f"-> CV RMSE={avg_rmse:.4f}"
        )

        if avg_rmse < best_score:
            best_score = avg_rmse
            best_cfg = cfg

    print(f"Best config from tuning: {best_cfg}")
    return best_cfg


